export function getStateBySlug(slug: string): StateData | undefined {
  return states.find(s => s.slug === slug)
}

export function calculateFederalTax(annualIncome: number): number {
  const taxableIncome = Math.max(0, annualIncome - federalStandardDeduction)
  let tax = 0
  for (const bracket of federalBrackets) {
    if (taxableIncome <= bracket.min) break
    const upper = bracket.max ?? Infinity
    const taxableInBracket = Math.min(taxableIncome, upper) - bracket.min
    tax += taxableInBracket * bracket.rate
  }
  return tax
}

export function calculateStateTax(annualIncome: number, state: StateData): number {
  if (!state.hasStateTax) return 0
  const taxableIncome = Math.max(0, annualIncome - state.standardDeduction)
  if (state.taxType === 'flat' && state.flatRate) {
    return taxableIncome * state.flatRate
  }
  if (state.brackets) {
    let tax = 0
    for (const bracket of state.brackets) {
      if (taxableIncome <= bracket.min) break
      const upper = bracket.max ?? Infinity
      const taxableInBracket = Math.min(taxableIncome, upper) - bracket.min
      tax += taxableInBracket * bracket.rate
    }
    return tax
  }
  return 0
}

export function calculateFICA(annualIncome: number): { socialSecurity: number; medicare: number } {
  const socialSecurity = Math.min(annualIncome, socialSecurityWageCap) * socialSecurityRate
  const medicare = annualIncome * medicareRate
  return { socialSecurity, medicare }
}
